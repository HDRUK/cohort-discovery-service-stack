#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
customisations_dir="${1:-${repo_root}/customisations}"
output_file="${2:-${repo_root}/generated/customisations.values.yaml}"

if [ ! -d "${customisations_dir}" ]; then
  echo "customisations-values: ${customisations_dir} is not a folder" >&2
  exit 1
fi

block_value() {
  local indent="$1" key="$2" file="$3"
  if [ -f "${customisations_dir}/${file}" ]; then
    echo "${indent}${key}: |"
    sed "s/^/${indent}  /" "${customisations_dir}/${file}"
  fi
}

section() {
  local name="$1"
  shift
  local body
  body="$("$@")"
  if [ -n "${body}" ]; then
    echo "${name}:"
    echo "${body}"
  fi
}

api_section() {
  block_value "  " authPhp api/auth.php
  block_value "  " claimsAccessControlPhp api/claimsaccesscontrol.php
  block_value "  " workgroupsPhp api/workgroups.php
}

nlp_section() {
  block_value "  " rulesJson nlp/rules.json
  block_value "  " mappingsJson nlp/mappings.json
}

keycloak_theme_files() {
  local theme_dir="${customisations_dir}/keycloak/theme" file
  [ -d "${theme_dir}" ] || return 0
  echo "  themeFiles:"
  while IFS= read -r file; do
    block_value "    " "\"${file#"${theme_dir}"/}\"" "keycloak/theme/${file#"${theme_dir}"/}"
  done < <(find "${theme_dir}" -type f ! -name '.*' | LC_ALL=C sort)
  block_value "    " '"login/resources/img/logo.svg"' web/branding/assets/logo.svg
  block_value "    " '"login/resources/img/icon.svg"' web/branding/assets/icon.svg
}

keycloak_section() {
  block_value "  " realmJson keycloak/realm.json
  keycloak_theme_files
}

mkdir -p "$(dirname "${output_file}")"
work_file="$(mktemp "${output_file}.XXXXXX")"
trap 'rm -f "${work_file}"' EXIT

{
  echo "# Generated by scripts/customisations-values.sh from ${customisations_dir#"${repo_root}"/}/. Edit those files, not this one."
  section api api_section
  section nlp nlp_section
  section keycloak keycloak_section
} > "${work_file}"

mv "${work_file}" "${output_file}"
trap - EXIT
echo "customisations-values: wrote ${output_file#"${repo_root}"/}"
